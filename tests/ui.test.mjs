import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {JSDOM} from "jsdom";
test("GitHub Pages interface: navigation, team registration, scoring and backup", async()=>{
 const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
 const dom=new JSDOM(html,{url:"https://example.org/Enjoy-AI/"});
 globalThis.window=dom.window;
 globalThis.document=dom.window.document;
 globalThis.localStorage=dom.window.localStorage;
 globalThis.FileReader=dom.window.FileReader;
 dom.window.scrollTo=()=>{};
 await import("../app.mjs");
 const q=s=>dom.window.document.querySelector(s);
 const click=s=>{const el=q(s);assert.ok(el,"Missing click target "+s);el.click();};
 const change=(s,value)=>{
  const input=q(s);assert.ok(input,"Missing input "+s);
  if(input.type==="checkbox")input.checked=!!value;else input.value=value;
  input.dispatchEvent(new dom.window.Event("change",{bubbles:true}));
 };
 const addTeam=(name,type)=>{
   click('[data-page="'+(type==="battle"?"teams-battle":"teams-invention")+'"]');
   q("#team-name").value=name;
   q("#team-member1").value=name+" Student 1";
   q("#team-member2").value=name+" Student 2";
   q("#team-coach").value="Coach "+name;
   q("#add-team").dispatchEvent(new dom.window.Event("submit",{bubbles:true,cancelable:true}));
 };
 assert.match(q("#content").textContent,/Tổng đội thi/);
 addTeam("Invention One","invention");
 assert.equal(JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1")).teams.length,1);
 click('[data-page="invention"]');
 change('[data-inv-task="compass"]',true);
 change("#inv-time","80");
 click('[data-final-inv="done"]');
 assert.match(q("#content").textContent,/HOÀN TẤT CHẤM/);
 click('[data-page="ranking"]');
 assert.match(q("#content").textContent,/50/);
 addTeam("Red Team","battle");
 addTeam("Blue Team","battle");
 click('[data-page="battle"]');
 assert.ok(q("#match-red"));
 click("[data-create-match]");
 assert.ok(q('[data-battle-field="red.tower"]'));
 change('[data-battle-field="red.tower"]',true);
 change("#battle-time","120");
 click('[data-final-battle="done"]');
 const state=JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1"));
 assert.equal(state.invention[0].status,"done");
 assert.equal(state.battles[0].status,"done");
 assert.equal(state.battles[0].red.tower,true);
 click('[data-page="random"]');
 click("[data-generate]");
 assert.ok(q(".slot-marker"));
 assert.equal(JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1")).layouts.length,1);
 dom.window.close();
});