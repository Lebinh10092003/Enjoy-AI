import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {JSDOM} from "jsdom";
test("GitHub Pages interface: navigation, team registration, scoring and backup", async()=>{
 const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
 const dom=new JSDOM(html,{url:"https://example.org/Enjoy-AI/"});
 globalThis.window=dom.window;
 globalThis.document=dom.window.document;
 globalThis.localStorage=dom.window.localStorage;
 globalThis.FileReader=dom.window.FileReader;
 let scrollCalls=0;
 dom.window.scrollTo=()=>{scrollCalls++;};
 await import("../app.mjs");
 const q=s=>dom.window.document.querySelector(s);
 const click=s=>{const el=q(s);assert.ok(el,"Missing click target "+s);el.click();};
 const change=(s,value)=>{
  const input=q(s);assert.ok(input,"Missing input "+s);
  if(input.type==="checkbox")input.checked=!!value;else input.value=value;
  input.dispatchEvent(new dom.window.Event("change",{bubbles:true}));
 };
 const addTeam=(name,type)=>{
   click('[data-page="'+(type==="battle"?"teams-battle":"teams-invention")+'"]');
   q("#team-name").value=name;
   q("#team-member1").value=name+" Student 1";
   q("#team-member2").value=name+" Student 2";
   q("#team-coach").value="Coach "+name;
   q("#add-team").dispatchEvent(new dom.window.Event("submit",{bubbles:true,cancelable:true}));
 };
 assert.match(q("#content").textContent,/Tổng đội thi/);
 addTeam("Invention One","invention");
 assert.equal(JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1")).teams.length,1);
 click('[data-page="invention"]');
 change('[data-inv-task="compass"]',true);
 change("#inv-time","80");
 click('[data-final-inv="done"]');
 assert.match(q("#content").textContent,/HOÀN TẤT CHẤM/);
 click('[data-page="ranking"]');
 assert.match(q("#content").textContent,/50/);
 addTeam("Red Team","battle");
 addTeam("Blue Team","battle");
 click('[data-page="battle"]');
 assert.ok(q("#match-red"));
 click("[data-create-match]");
 assert.ok(q('[data-battle-field="red.tower"]'));
 change('[data-battle-field="red.tower"]',true);
 change("#battle-time","120");
 click('[data-final-battle="done"]');
 const state=JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1"));
 assert.equal(state.invention[0].status,"done");
 assert.equal(state.battles[0].status,"done");
 assert.equal(state.battles[0].red.tower,true);
 click('[data-page="random"]');
 assert.match(q("#content").textContent,/7 nhiệm vụ/);
 assert.match(q("#content").textContent,/3 vật cản/);
 assert.equal(q("#layout-task-count"),null);
 assert.equal(q("#layout-obstacles"),null);
 const actionButton=q("[data-generate]");
 const arenaBackground=q(".arena-background");
 const scrollBeforeGenerate=scrollCalls;
 click("[data-generate]");
 assert.equal(scrollCalls,scrollBeforeGenerate,"Random must not scroll the window to the top");
 assert.equal(q("[data-generate]"),actionButton,"Random controls must retain their DOM nodes");
 assert.equal(q(".arena-background"),arenaBackground,"Arena image must not be reloaded");
 assert.ok(q(".slot-marker"));
 assert.equal(dom.window.document.querySelectorAll(".mission-marker").length,7);
 assert.equal(dom.window.document.querySelectorAll(".obstacle-rect").length,3);
 const loadLayouts=()=>JSON.parse(localStorage.getItem("enjoy-ai-2026-competition-desk-v1")).layouts;
 let layouts=loadLayouts();
 assert.equal(layouts.length,1);
 assert.equal(layouts[0].tasks.length,7);
 assert.equal(layouts[0].obstacles.length,3);
 assert.ok(layouts[0].obstacles.every(id=>/^O[1-9]$/.test(id)));
 const first=layouts[0];
 assert.equal(q("#layout-seed").value,"","New random should leave seed input empty");
 // Regression: the original button reused the previous seed after rendering.
 click("[data-generate]");
 assert.equal(scrollCalls,scrollBeforeGenerate,"Repeated random must not move scroll position");
 assert.equal(q("[data-generate]"),actionButton,"Repeated random must not rerender toolbar");
 assert.equal(q(".arena-background"),arenaBackground,"Repeated random must preserve field image");
 layouts=loadLayouts();
 assert.equal(layouts.length,2);
 assert.notEqual(layouts[0].seed,first.seed,"Each new random must use a fresh seed");
 assert.notDeepEqual(
  {tasks:layouts[0].tasks,obstacles:layouts[0].obstacles},
  {tasks:first.tasks,obstacles:first.obstacles},
  "The next random must change the actual task/obstacle arrangement"
 );
 assert.equal(dom.window.document.querySelectorAll(".mission-marker").length,7);
 assert.equal(dom.window.document.querySelectorAll(".obstacle-rect").length,3);
 assert.equal(q("#layout-seed").value,"");
 change("#selected-layout",first.id);
 assert.equal(scrollCalls,scrollBeforeGenerate,"Selecting a saved random layout must not scroll to the top");
 assert.equal(q(".arena-background"),arenaBackground,"Saved layout selection must preserve arena image");
 assert.equal(q("[data-generate]"),actionButton);
 // The explicit replay action remains deterministic.
 q("#layout-seed").value=first.seed;
 click("[data-generate-seed]");
 layouts=loadLayouts();
 assert.equal(layouts.length,3);
 assert.equal(layouts[0].seed,first.seed);
 assert.deepEqual(layouts[0].tasks,first.tasks);
 assert.deepEqual(layouts[0].obstacles,first.obstacles);
 assert.equal(q("#layout-seed").value,first.seed);
 // The normal random action ignores seed text and uses a new one.
 click("[data-generate]");
 layouts=loadLayouts();
 assert.equal(layouts.length,4);
 assert.notEqual(layouts[0].seed,first.seed);
 assert.equal(q("#layout-seed").value,"");
 const arenaImageBeforeAgain=q(".arena-background");
 click("[data-generate-board]");
 layouts=loadLayouts();
 assert.equal(layouts.length,5,"Arena header Random lại must create another layout");
 assert.equal(layouts[0].tasks.length,7);
 assert.equal(layouts[0].obstacles.length,3);
 assert.equal(q(".arena-background"),arenaImageBeforeAgain,"Board random button must not recreate the image");
 assert.equal(scrollCalls,scrollBeforeGenerate,"Board random button must not scroll to page top");
 dom.window.close();
});